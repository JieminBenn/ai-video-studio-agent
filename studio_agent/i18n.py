def t(text: str, lang: str) -> str:
    """Translate a UI chrome string. ``en`` is passthrough; unknown strings fall
    back to the English source so missing translations are visible, not fatal."""
    if lang != "zh":
        return text
    return UI_STRINGS.get(text.strip(), text)


def lang_from_cookie_header(cookie_header: str | None) -> str:
    """Resolve the ``studioLang`` cookie to ``en`` (default) or ``zh``."""
    if not cookie_header:
        return "en"
    jar = SimpleCookie()
    try:
        jar.load(cookie_header)
    except Exception:
        return "en"
    morsel = jar.get("studioLang")
    value = morsel.value if morsel else ""
    return "zh" if value == "zh" else "en"
